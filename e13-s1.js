/* E1.3(1) 整數、數位與點陣：做一做1、練習1–4（工作紙 p.12）。
   Answers: approved Answer_Key.md L102–L106. Inserted after (1) 例題1 in worksheet order. */
(function () {
  'use strict';
  const A = window.AL;
  if (!A) return;
  const { M, qk, tx, C, MUTED, known, find, eqLine, nbox, trRow, stepPage, tryPages, practice } = A;
  const S = '1', SEC = 'E1.3(1)';

  // ---------- 做一做 1 ----------
  const t1Q = [`兩個${qk('連續正整數')}的${qk('平方和')}為 ${qk('145')}，求這兩個整數。`];
  const t1P1 = h => stepPage(h, {
    keys: true,
    items: [
      { k: '審', html: known('兩個數是<b>連續</b>的<b>正整數</b>。') },
      { k: '審', html: known('它們的平方和為 145。') },
      { k: '審', html: find('這兩個整數。') },
      { k: '設', html: `設較小的數為 ${M('n')}。${nbox('較小的數', 'n')}` },
      { k: '設', html: `較大的數為 ${M('n+1')}。${nbox('較大的數', 'n+1')}` },
      { k: '表', html: trRow('較小數的平方', 'n^2') },
      { k: '表', html: trRow('較大數的平方', '(n+1)^2') },
      { k: '列', html: eqLine('n^2+(n+1)^2=145', '<span class="lbl eq">方程</span>') }
    ],
    onStep: (s, h) => {
      const el = h.querySelector(`[data-step="${s}"]`);
      if (s === 4 || s === 5) A.anim().popIn(el.querySelector('.nbox'));
      if (s === 6 || s === 7) A.anim().lineDraw(el.querySelector('.tr-line'));
    }
  });
  const t1Rows = [[
    { k: '設', h: `設較小的數為 ${M('n')}，則較大的數為 ${M('n+1')}（${M('n')} 為正整數）。` },
    { k: '列', l: 'n^2+(n+1)^2', r: '145' },
    { k: '解', l: 'n^2+n^2+2n+1', r: '145' },
    { l: '2n^2+2n-144', r: '0' },
    { l: 'n^2+n-72', r: '0' },
    { l: '(n-8)(n+9)', r: '0' },
    { h: `${M('n=8')} 或 ${M('n=-9')}` }
  ], [
    { k: '驗', h: `${M('n')} 為正整數，${M('n=-9')} 不合，捨去。` },
    { h: `代回：${M('8^2+9^2=64+81=145')} ✓` },
    { k: '答', h: '這兩個整數是 8 和 9。', cls: 'answer' }
  ]];
  const t1Trap = [`「平方和」是先平方再相加：${M('n^2+(n+1)^2')}，不是 ${M('(n+n+1)^2')}。`];

  // ---------- 練習 1 ----------
  const p1Q = ['一個兩位正整數的個位數比十位數大 3，兩個數字之積是 18。求這個兩位數。'];
  const p1Rows = [[
    { k: '設', h: `設十位數為 ${M('t')}，則個位數為 ${M('t+3')}。` },
    { k: '列', l: 't(t+3)', r: '18' },
    { k: '解', l: 't^2+3t-18', r: '0' },
    { l: '(t+6)(t-3)', r: '0' },
    { h: `${M('t=3')} 或 ${M('t=-6')}` }
  ], [
    { k: '驗', h: `數字是 0 至 9 的整數，${M('t=-6')} 不合，捨去。` },
    { h: `${M('t=3')}：個位數 6，${M('3\\times6=18')} ✓` },
    { k: '答', h: '這個兩位數是 36。', cls: 'answer' }
  ]];
  const p1Trap = ['答「3 和 6」：題目求的是<span class="hl">兩位數</span> 36。'];

  // ---------- 練習 2 ----------
  const p2Q = ['兩個連續正偶數，其和的平方比它們的平方和大 48。求這兩個偶數。'];
  const p2Rows = [[
    { k: '設', h: `設較小的偶數為 ${M('n')}，則較大的偶數為 ${M('n+2')}（${M('n')} 為正偶數）。` },
    { k: '列', l: '(n+n+2)^2-[n^2+(n+2)^2]', r: '48' },
    { k: '解', l: '4n^2+8n+4-2n^2-4n-4', r: '48' },
    { l: '2n^2+4n-48', r: '0' },
    { l: 'n^2+2n-24', r: '0' },
    { l: '(n+6)(n-4)', r: '0' },
    { h: `${M('n=4')} 或 ${M('n=-6')}` }
  ], [
    { k: '驗', h: `${M('n')} 為正偶數，${M('n=-6')} 不合，捨去。` },
    { h: `代回：${M('(4+6)^2=100')}，${M('4^2+6^2=52')}，${M('100-52=48')} ✓` },
    { k: '答', h: '這兩個偶數是 4 和 6。', cls: 'answer' }
  ]];
  const p2Trap = ['連續偶數相差 <span class="hl">2</span>，不是 1。', `「和的平方」${M('(n+n+2)^2')} 與「平方和」${M('n^2+(n+2)^2')} 不同。`];

  // ---------- 練習 3 ----------
  const p3Q = ['一個兩位正整數的十位數比個位數大 2。兩個數字之積比這個兩位數小 40。求這個兩位數的所有可能值。'];
  const p3Rows = [[
    { k: '設', h: `設個位數為 ${M('u')}，則十位數為 ${M('u+2')}。` },
    { k: '表', h: `這個兩位數為 ${M('10(u+2)+u=11u+20')}。` },
    { k: '列', l: 'u(u+2)', r: '(11u+20)-40' },
    { k: '解', l: 'u^2+2u', r: '11u-20' },
    { l: 'u^2-9u+20', r: '0' },
    { l: '(u-4)(u-5)', r: '0' },
    { h: `${M('u=4')} 或 ${M('u=5')}` }
  ], [
    { k: '驗', h: `${M('u=4')}：64，數字之積 24，${M('64-24=40')} ✓` },
    { h: `${M('u=5')}：75，數字之積 35，${M('75-35=40')} ✓` },
    { k: '答', h: '這個兩位數是 64 或 75。', cls: 'answer' }
  ]];
  const p3Trap = [`兩位數不是 ${M('(u+2)+u')}：十位數要<span class="hl">乘 10</span>。`, '「積比兩位數小 40」：積 ＝ 兩位數 − 40。'];

  // ---------- 練習 4（點陣） ----------
  const p4Q = [`以下點陣依同一規律排列，由左至右為第 1 至 4 幅。第 ${M('n')} 幅的點數為 ${M('\\dfrac{n(n+1)}{2}')}。`, '(a) 哪一幅有 105 點？　(b) 是否有一幅剛好有 254 點？說明理由。'];
  function dotsSVG() {
    let g = '';
    [1, 2, 3, 4].forEach((n, i) => {
      const cx = 70 + i * 120, base = 92;
      for (let row = 1; row <= n; row++) for (let j = 0; j < row; j++) {
        g += `<circle cx="${cx - (row - 1) * 7 + j * 14}" cy="${base - (n - row) * 13}" r="5" fill="${C}"/>`;
      }
      g += tx(cx, 116, `第 ${n} 幅`, 14, MUTED, 600);
    });
    g += tx(530, 92, '⋯', 20, MUTED);
    return `<svg viewBox="0 0 560 126" role="img" aria-label="三角點陣第 1 至 4 幅：1、3、6、10 點">${g}</svg>`;
  }
  const p4Rows = [[
    { h: '<b>(a)</b>' },
    { k: '列', l: '\\dfrac{n(n+1)}{2}', r: '105' },
    { k: '解', l: 'n^2+n-210', r: '0' },
    { l: '(n-14)(n+15)', r: '0' },
    { k: '驗', h: `${M('n=14')} 或 ${M('n=-15')}；幅數是正整數，${M('n=-15')} 不合。` },
    { k: '答', h: '(a) 第 14 幅有 105 點。', cls: 'answer' }
  ], [
    { h: '<b>(b)</b>' },
    { k: '列', l: '\\dfrac{n(n+1)}{2}', r: '254' },
    { k: '解', l: 'n^2+n-508', r: '0' },
    { l: 'n', r: '\\dfrac{-1\\pm\\sqrt{2033}}{2}' },
    { k: '驗', h: `${M('45^2=2025')}，${M('46^2=2116')}，${M('\\sqrt{2033}')} 不是整數，${M('n')} 不是正整數（第 22 幅 253 點，第 23 幅 276 點）。` },
    { k: '答', h: '(b) 沒有一幅剛好有 254 點。', cls: 'answer' }
  ]];
  const p4Trap = [`${M('n')} 是幅數，必須是<span class="hl">正整數</span>；解出不是整數，就表示沒有這一幅。`];

  A.insertAfter('(1) 例題1 · 解・驗・答', [
    ...tryPages(S, `${SEC}　做一做 1`, '(1) 做一做1', t1Q, t1P1, t1Rows, t1Trap),
    practice(S, `${SEC}　練習 1`, '(1) 練習1', p1Q, { cols: p1Rows, trap: p1Trap }),
    practice(S, `${SEC}　練習 2`, '(1) 練習2', p2Q, { cols: p2Rows, trap: p2Trap }),
    practice(S, `${SEC}　練習 3`, '(1) 練習3', p3Q, { cols: p3Rows, trap: p3Trap }),
    practice(S, `${SEC}　練習 4`, '(1) 練習4', p4Q, { cols: p4Rows, trap: p4Trap, figHTML: dotsSVG(), figCls: 'short' })
  ]);
})();
